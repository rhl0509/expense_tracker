export type Country = { iso: string; dial: string; name: string; example: string };
export type ContinentGroup = { label: string; countries: Country[] };

export const DEFAULT_ISO = 'KR';

export function dialOf(iso: string): string {
  return findCountry(iso)?.dial ?? '+82';
}

export function findCountry(iso: string): Country | undefined {
  for (const g of COUNTRY_GROUPS) {
    const hit = g.countries.find((c) => c.iso === iso);
    if (hit) return hit;
  }
  return undefined;
}

